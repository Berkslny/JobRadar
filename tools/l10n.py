"""Extract t("…") keys from the Swift sources, check the Turkish table and write L10nTurkish.swift.

usage: l10n.py keys      list the keys (JSON)
       l10n.py check     report missing / unused / placeholder mismatches
       l10n.py write     generate app/JobRadar/L10nTurkish.swift
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "JobRadar" if (ROOT / "JobRadar").is_dir() else ROOT / "app" / "JobRadar"
OUT = SRC / "L10nTurkish.swift"
CALL = re.compile(r'(?<![\w.])t\(\s*"((?:[^"\\]|\\.)*)"', re.S)


def unescape(s: str) -> str:
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "n":
                out.append("\n")
            elif n == "t":
                out.append("\t")
            elif n == "(":
                raise ValueError(f"interpolation in key: {s!r}")
            elif n == "u":
                m = re.match(r"\\u\{([0-9a-fA-F]+)\}", s[i:])
                out.append(chr(int(m.group(1), 16)))
                i += len(m.group(0))
                continue
            else:
                out.append(n)
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def keys() -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for path in sorted(SRC.glob("*.swift")):
        if path.name == OUT.name:
            continue
        text = path.read_text(encoding="utf-8")
        for m in CALL.finditer(text):
            key = unescape(m.group(1))
            line = text.count("\n", 0, m.start()) + 1
            found.setdefault(key, []).append(f"{path.name}:{line}")
    return found


def placeholders(s: str) -> tuple[int, set[int]]:
    seq = len(re.findall(r"%@", s))
    pos = {int(x) for x in re.findall(r"%(\d)\$@", s)}
    return seq, pos


def swift_literal(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def load_table() -> dict[str, str]:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import tr_table  # noqa: PLC0415

    return tr_table.TR


def check(found, table) -> int:
    bad = 0
    for key, where in found.items():
        if key not in table:
            print(f"MISSING  {where[0]}: {key!r}")
            bad += 1
            continue
        kseq, kpos = placeholders(key)
        tseq, tpos = placeholders(table[key])
        n = kseq + len(kpos)
        if kpos:
            print(f"KEY USES POSITIONAL  {key!r}")
            bad += 1
        if tpos:
            if tseq or tpos != set(range(1, n + 1)):
                print(f"PLACEHOLDERS  {key!r} -> {table[key]!r}")
                bad += 1
        elif tseq != kseq:
            print(f"PLACEHOLDERS  {key!r} -> {table[key]!r}")
            bad += 1
    for key in table:
        if key not in found:
            print(f"UNUSED   {key!r}")
    print(f"{len(found)} keys, {len(table)} translations, {bad} problems")
    return bad


def write(found, table) -> None:
    items = [(k, table[k]) for k in sorted(found)]
    chunk = 90
    parts = [items[i:i + chunk] for i in range(0, len(items), chunk)]
    lines = ["import Foundation", "",
             "// Generated by tools/l10n.py from the t(\"…\") calls in the sources. Do not edit by hand:",
             "// change tools/tr_table.py and run the script again.", "",
             "nonisolated extension L10n {",
             "    /// English text -> Turkish text.",
             "    static let turkish: [String: String] = {",
             "        var table: [String: String] = [:]",
             f"        table.reserveCapacity({len(items)})",
             "        for part in [" + ", ".join(f"turkish{i + 1}" for i in range(len(parts))) + "] {",
             "            table.merge(part) { first, _ in first }",
             "        }",
             "        return table",
             "    }()", ""]
    for i, part in enumerate(parts):
        lines.append(f"    private static let turkish{i + 1}: [String: String] = [")
        for k, v in part:
            lines.append(f"        {swift_literal(k)}:")
            lines.append(f"            {swift_literal(v)},")
        lines.append("    ]")
        lines.append("")
    lines[-1] = "}"
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(items)} entries, {len(parts)} parts)")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    found = keys()
    if cmd == "keys":
        print(json.dumps(sorted(found), ensure_ascii=False, indent=0))
    elif cmd == "check":
        sys.exit(1 if check(found, load_table()) else 0)
    elif cmd == "write":
        table = load_table()
        if check(found, table):
            sys.exit(1)
        write(found, table)
